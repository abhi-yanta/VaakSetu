import 'dart:ui';

enum FieldConfidence {
  green,
  yellow,
  red,
}

enum BlankPosition {
  below,
  right,
  unclear,
}

class FormFieldDefinition {
  final String key;
  final String defaultLabel;
  final List<String> keywords;
  final Map<String, String> labels;
  final Map<String, String> spokenHelp;

  const FormFieldDefinition({
    required this.key,
    required this.defaultLabel,
    required this.keywords,
    required this.labels,
    required this.spokenHelp,
  });
}

class FormFieldItem {
  final String id;
  final String fieldKey;
  final String label;
  final String translatedLabel;
  final String matchedText;
  final double matchConfidence;
  final Rect boundingBox;
  final Rect? blankRegion;
  final FieldConfidence confidence;
  final BlankPosition blankPosition;
  final int readingOrder;

  const FormFieldItem({
    required this.id,
    required this.fieldKey,
    required this.label,
    required this.translatedLabel,
    required this.matchedText,
    required this.matchConfidence,
    required this.boundingBox,
    this.blankRegion,
    required this.confidence,
    required this.blankPosition,
    required this.readingOrder,
  });

  FormFieldItem copyWith({
    String? id,
    String? fieldKey,
    String? label,
    String? translatedLabel,
    String? matchedText,
    double? matchConfidence,
    Rect? boundingBox,
    Rect? blankRegion,
    FieldConfidence? confidence,
    BlankPosition? blankPosition,
    int? readingOrder,
  }) {
    return FormFieldItem(
      id: id ?? this.id,
      fieldKey: fieldKey ?? this.fieldKey,
      label: label ?? this.label,
      translatedLabel: translatedLabel ?? this.translatedLabel,
      matchedText: matchedText ?? this.matchedText,
      matchConfidence: matchConfidence ?? this.matchConfidence,
      boundingBox: boundingBox ?? this.boundingBox,
      blankRegion: blankRegion ?? this.blankRegion,
      confidence: confidence ?? this.confidence,
      blankPosition: blankPosition ?? this.blankPosition,
      readingOrder: readingOrder ?? this.readingOrder,
    );
  }
}

